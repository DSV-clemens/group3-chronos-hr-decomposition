"""
Phase 4c: DLinear baseline (label 'dlinear') - trained on a separate corpus.

Reference: Zeng et al., "Are Transformers Effective for Time Series
Forecasting Anyway?" (AAAI 2023) - the linear model that matched or beat
foundation-model-style architectures on long-horizon forecasting.

Design (information budget comparable to the foundation model):
  - ONE global ridge regression per scenario, fitted on standardised
    sliding windows from the TRAINING CORPUS generated by
    `src/03_synthesis/generate_dlinear_corpus.py` (default: 1500 series,
    seed 6677 - the benchmark seed 67 series are never seen in training).
  - Input: last `--input-len` (default 64) standardised context values.
    Output: the next `horizon` values (direct multi-output).
  - Evaluation: zero-shot on the full benchmark (all 150 series per
    scenario), fully paired with chronos2 / naive / decomp / decomp_acf.
  - Quantile band from the per-horizon training residual scale (normal
    approximation).

Weights (W, sigma per scenario) are persisted to --weights-dir
(default results/dlinear_weights) and committed to the repo, so the
forecast step is reproducible without regenerating the corpus. Use
--train to (re)fit the weights; without --train the script loads the
persisted weights and only runs the forecast step.

Outputs (same conventions as run_forecast.py):
    forecasts_dlinear_{scenario}.parquet
    metrics_per_series.csv / summary_scenario.csv (A/B-safe per label)
    manifest_dlinear.json

Usage:
    python src/04_forecast/run_forecast_dlinear.py --train      # fit + forecast
    python src/04_forecast/run_forecast_dlinear.py              # forecast only
    python src/04_forecast/run_forecast_dlinear.py --train --max-series 5
"""
from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from run_forecast import (DEFAULT_QUANTILES, load_scenario, split_context,
                          series_metrics, save_df, _norm_ppf)

LABEL = "dlinear"
WEIGHTS_DIR = Path("results/dlinear_weights")


# ------------------------------------------------------------------ training

def _series_windows(y: np.ndarray, n_in: int, horizon: int
                    ) -> tuple[np.ndarray, np.ndarray]:
    """Standardised sliding windows from one series (full length)."""
    n_pairs = len(y) - n_in - horizon + 1
    if n_pairs <= 0:
        return np.empty((0, n_in + 1)), np.empty((0, horizon))
    X = np.empty((n_pairs, n_in + 1))
    Y = np.empty((n_pairs, horizon))
    for s in range(n_pairs):
        xw = y[s:s + n_in]
        yw = y[s + n_in:s + n_in + horizon]
        m = float(xw.mean())
        sig = float(xw.std()) or 1.0
        X[s, :n_in] = (xw - m) / sig
        X[s, n_in] = 1.0
        Y[s] = (yw - m) / sig
    return X, Y


def train_dlinear(corpus_dir: Path, scenarios: list[str], n_in: int,
                  horizon: int, ridge: float, max_train_series: int | None = None
                  ) -> dict[str, dict]:
    """Fit one global ridge regression per scenario on the corpus.

    Accumulates X^T X and X^T Y in per-series chunks so the full window
    matrix is never materialised (memory-safe for large corpora).
    Returns {scenario: {"W": (n_in+1, horizon), "sigma": (horizon,),
    "n_windows": int}}.
    """
    fits: dict[str, dict] = {}
    for scen in scenarios:
        t0 = time.perf_counter()
        path = corpus_dir / f"synthetic_hr_mmash_{scen}.parquet"
        if not path.exists():
            alt = corpus_dir / f"synthetic_hr_mmash_{scen}.csv.gz"
            if not alt.exists():
                raise FileNotFoundError(
                    f"corpus file for '{scen}' not found in {corpus_dir} - "
                    f"run src/03_synthesis/generate_dlinear_corpus.py first")
            df = pd.read_csv(alt)
        else:
            df = pd.read_parquet(path)
        ids = sorted(df["series_id"].unique())
        if max_train_series:
            ids = ids[:max_train_series]
        print(f"[Train] '{scen}': loading corpus ({len(ids)} series) ...", flush=True)

        A = np.zeros((n_in + 1, n_in + 1))
        B = np.zeros((n_in + 1, horizon))
        n_windows = 0
        var_acc = np.zeros(horizon)
        n_done = 0
        t_pass = time.perf_counter()
        for sid in ids:
            g = df[df["series_id"] == sid]
            y = g.sort_values("t")["hr"].to_numpy(dtype=np.float64)
            X, Y = _series_windows(y, n_in, horizon)
            if len(X) == 0:
                continue
            A += X.T @ X
            B += X.T @ Y
            n_windows += len(X)
            n_done += 1
            if n_done % 100 == 0:
                print(f"[Train] '{scen}': pass 1/2, {n_done}/{len(ids)} series "
                      f"({time.perf_counter() - t_pass:.0f}s)", flush=True)
        A += ridge * np.eye(n_in + 1)
        W = np.linalg.solve(A, B)
        # second pass: per-horizon residual variance
        n_done = 0
        t_pass = time.perf_counter()
        for sid in ids:
            g = df[df["series_id"] == sid]
            y = g.sort_values("t")["hr"].to_numpy(dtype=np.float64)
            X, Y = _series_windows(y, n_in, horizon)
            if len(X) == 0:
                continue
            R = Y - X @ W
            var_acc += (R ** 2).sum(axis=0)
            n_done += 1
            if n_done % 100 == 0:
                print(f"[Train] '{scen}': pass 2/2, {n_done}/{len(ids)} series "
                      f"({time.perf_counter() - t_pass:.0f}s)", flush=True)
        sigma = np.sqrt(np.maximum(var_acc / n_windows, 1e-12))
        fits[scen] = {"W": W, "sigma": sigma, "n_windows": n_windows}
        print(f"[Train] '{scen}': done, {n_windows} windows "
              f"({time.perf_counter() - t0:.0f}s total)")
    return fits


def save_weights(fits: dict[str, dict], weights_dir: Path) -> None:
    weights_dir.mkdir(parents=True, exist_ok=True)
    for scen, f in fits.items():
        np.save(weights_dir / f"W_{scen}.npy", f["W"])
        np.save(weights_dir / f"sigma_{scen}.npy", f["sigma"])


def load_weights(weights_dir: Path, scenarios: list[str]) -> dict[str, dict]:
    fits = {}
    for scen in scenarios:
        W = np.load(weights_dir / f"W_{scen}.npy")
        sigma = np.load(weights_dir / f"sigma_{scen}.npy")
        fits[scen] = {"W": W, "sigma": sigma}
    return fits


# ------------------------------------------------------------------ forecast

def forecast_dlinear(ctx: pd.DataFrame, horizon: int, quantiles: list[float],
                     W: np.ndarray, sigma: np.ndarray, n_in: int
                     ) -> pd.DataFrame:
    """Apply the fitted linear map to each context window (zero-shot)."""
    z = {q: _norm_ppf(q) for q in quantiles}
    rows = []
    for sid, g in ctx.groupby("series_id"):
        y = g.sort_values("t")["hr"].to_numpy(dtype=float)
        xw = y[-n_in:]
        m = float(xw.mean())
        sig = float(xw.std()) or 1.0
        xn = np.concatenate([(xw - m) / sig, [1.0]])
        pred = (xn @ W) * sig + m  # (horizon,)
        for h in range(horizon):
            row = {"series_id": sid}
            for q in quantiles:
                row[f"q{q:g}"] = pred[h] + z[q] * sigma[h] * sig
            rows.append(row)
    return pd.DataFrame(rows)


# ------------------------------------------------------------------ main

def main() -> None:
    ap = argparse.ArgumentParser(
        description="DLinear baseline (global ridge on the corpus, "
                    "zero-shot forecast on the benchmark)")
    ap.add_argument("--input-dir", default="data/synthetic")
    ap.add_argument("--corpus-dir", default="data/dlinear_corpus")
    ap.add_argument("--weights-dir", default=str(WEIGHTS_DIR))
    ap.add_argument("--out-dir", default="results")
    ap.add_argument("--scenarios", nargs="+", default=["residual", "trend", "none"])
    ap.add_argument("--context", type=int, default=512)
    ap.add_argument("--horizon", type=int, default=256)
    ap.add_argument("--quantiles", nargs="+", type=float, default=DEFAULT_QUANTILES)
    ap.add_argument("--input-len", type=int, default=64)
    ap.add_argument("--ridge", type=float, default=1.0)
    ap.add_argument("--train", action="store_true",
                    help="fit the weights on the corpus (otherwise load "
                         "persisted weights from --weights-dir)")
    ap.add_argument("--max-train-series", type=int, default=None)
    ap.add_argument("--max-series", type=int, default=None)
    args = ap.parse_args()

    input_dir, corpus_dir = Path(args.input_dir), Path(args.corpus_dir)
    weights_dir = Path(args.weights_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    quantiles = sorted(args.quantiles)

    t_start = time.perf_counter()

    if args.train:
        fits = train_dlinear(corpus_dir, args.scenarios, args.input_len,
                             args.horizon, args.ridge, args.max_train_series)
        save_weights(fits, weights_dir)
        print(f"[Train] weights saved to {weights_dir}")
    else:
        if not (weights_dir / f"W_{args.scenarios[0]}.npy").exists():
            raise SystemExit(
                f"No persisted weights in {weights_dir}. Run with --train "
                f"(and generate the corpus first: "
                f"src/03_synthesis/generate_dlinear_corpus.py).")
        fits = load_weights(weights_dir, args.scenarios)
        print(f"[Load] weights from {weights_dir}")

    metric_rows, n_series_map = [], {}
    for scen in args.scenarios:
        df = load_scenario(input_dir, scen)
        ctx, truth = split_context(df, args.context, args.max_series)
        n = int(ctx["series_id"].nunique())
        horizon = min(args.horizon, len(truth) // max(n, 1))
        print(f"\n=== Scenario '{scen}': {n} series | context {args.context} | "
              f"horizon {horizon} | DLinear (zero-shot) ===")

        t0 = time.perf_counter()
        fc = forecast_dlinear(ctx, horizon, quantiles,
                              fits[scen]["W"], fits[scen]["sigma"], args.input_len)
        fc["t"] = args.context + fc.groupby("series_id").cumcount()
        fc = fc.sort_values(["series_id", "t"]).reset_index(drop=True)
        fc = fc.merge(truth[["series_id", "t", "hr"]], on=["series_id", "t"],
                      how="inner")
        fc = fc.rename(columns={"hr": "actual"}).assign(scenario=scen)
        save_df(fc, out_dir / f"forecasts_{LABEL}_{scen}")

        for sid, g in fc.groupby("series_id"):
            m = series_metrics(g["actual"].to_numpy(),
                               g[[f"q{q:g}" for q in quantiles]].to_numpy(),
                               quantiles)
            metric_rows.append({"label": LABEL, "scenario": scen,
                                "series_id": int(sid), **m})
        n_series_map[scen] = n
        print(f"[Run] {LABEL} on '{scen}' finished in "
              f"{time.perf_counter() - t0:.1f}s")

    metrics = pd.DataFrame(metric_rows)
    metrics_path = out_dir / "metrics_per_series.csv"
    if metrics_path.exists():
        old = pd.read_csv(metrics_path)
        metrics = pd.concat([old[old["label"] != LABEL], metrics],
                            ignore_index=True)
    metrics.to_csv(metrics_path, index=False)

    summary = (metrics.groupby(["label", "scenario"])[["mae", "wql", "coverage"]]
               .median().reset_index())
    summary["n_series"] = metrics.groupby(["label", "scenario"]).size().to_numpy()
    summary["nominal"] = quantiles[-1] - quantiles[0]
    summary.to_csv(out_dir / "summary_scenario.csv", index=False)

    manifest = {
        "label": LABEL,
        "model": "DLinear-style global ridge regression (standardised sliding "
                 "windows, direct multi-output)",
        "reference": "Zeng et al., AAAI 2023",
        "quantiles": quantiles,
        "context": args.context, "horizon": args.horizon,
        "input_len": args.input_len, "ridge": args.ridge,
        "trained_on": f"separate corpus in {corpus_dir} "
                       "(generate_dlinear_corpus.py, seed 6677); benchmark "
                       "series (seed 67) never seen in training",
        "weights_dir": str(weights_dir),
        "n_train_windows": {s: int(f.get("n_windows", -1)) for s, f in fits.items()},
        "n_series": n_series_map,
        "scenarios": args.scenarios,
        "runtime_sec": round(time.perf_counter() - t_start, 1),
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    manifest_path = out_dir / f"manifest_{LABEL}.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False))

    print("\n=== Summary (median per scenario, all labels) ===")
    print(summary.to_string(index=False))
    print(f"\n[Manifest] {manifest_path}")


if __name__ == "__main__":
    main()
